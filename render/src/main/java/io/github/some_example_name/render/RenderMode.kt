package io.github.some_example_name.render

/**
 * Как рисуется мир.
 *
 * Режим у каждого экрана свой и едет в WorldRenderer с кадром (RenderFrame.mode):
 * симуляция и редактор генома выбирают его своими списками независимо друг от друга, а
 * мир за главным меню всегда рисуется реалистично. Глобальной настройки нет намеренно —
 * раньше она была, и выбор в симуляции протекал и в меню, и в редактор.
 *
 * Раньше вместо него был один флаг usePostProcess — кнопка «рисовать лучи». Пока режимов
 * было два, флаг читался и как «нужен ли постпроцесс», и как «рисовать ли отладку поверх»:
 * это было одно и то же. С третьим режимом эти вопросы разошлись — у ностальгического нет
 * ни постпроцесса, ни отладочных линий, — поэтому каждый вопрос теперь задаётся отдельно,
 * свойствами ниже, а не сравнением с конкретным режимом по месту.
 *
 * Порядок констант — порядок пунктов в выпадающем списке.
 *
 * [dumpCode] — номер режима в дампе сцены (RenderSceneDump). Отдельным числом, а не
 * ordinal: на его месте в дампе раньше лежал байт usePostProcess (0 — без постпроцесса,
 * 1 — с ним), и коды первых двух режимов совпадают с ним, чтобы старые дампы читались без
 * миграции. Порядок в списке от этого не зависит.
 */
enum class RenderMode(val dumpCode: Int) {

    /** Текстуры клеток плюс постпроцесс: собель, аберрация, блюр, феромоны, виньетка. */
    REALISTIC(dumpCode = 1),

    /** Плоские клетки, а поверх — связи и направления (их рисует :core). */
    DEBUG(dumpCode = 0),

    /** Кружки по диаграмме Вороного с ядром и тёмным контуром, как в первых версиях. */
    NOSTALGIC(dumpCode = 2);

    /** Гонять кадр через постпроцесс (собель, аберрация, блюр, феромоны, виньетка). */
    val usesPostProcess: Boolean get() = this == REALISTIC

    /**
     * Рисовать поверх мира связи и направления клеток.
     *
     * Читается и потоком симуляции: по нему сборщик снимка решает, заполнять ли буфер
     * связей и направляющие углы — в остальных режимах это работа впустую.
     */
    val drawsDebugOverlay: Boolean get() = this == DEBUG

    companion object {
        /** Режим по коду из дампа; неизвестный код — значение по умолчанию. */
        fun fromDumpCode(code: Int): RenderMode =
            entries.firstOrNull { it.dumpCode == code } ?: REALISTIC
    }
}
