package io.github.some_example_name.old.commands

/**
 * Порядок отложенных команд мира — один и тот же при любом числе воркеров.
 *
 * ЗАЧЕМ
 * -----
 * Параллельные стадии раздают работу динамически (ParallelExecutor): организм или блок
 * берёт тот воркер, кто первым освободился, и команды мира (деление, смерть, новые
 * связи) ложатся в буфер ЭТОГО воркера. Применялись буферы по номеру воркера, поэтому
 * порядок применения — а значит, и индексы новых клеток — зависел от того, кто какую
 * работу успел схватить. Мир расходился от запуска к запуску уже через секунду, и повтор
 * бага по журналу (BugReplay) не совпадал с игрой, хотя все команды игрока совпадали.
 *
 * КАК
 * ---
 * У каждой команды есть ключ «номер стадии, номер работы». Стадия (ThreadManager)
 * выставляет его буферу перед каждой работой, буфер запоминает его у каждой команды
 * (WorldCommandBuffer.orderKeys), а WorldCommandsManager применяет буферы слиянием по
 * ключу: «стадия 1 работа 0, стадия 1 работа 1, …» — ровно так, как если бы всё
 * считал один поток, кто бы что ни взял.
 *
 * Слияние корректно потому, что каждый буфер уже отсортирован по ключу: воркер берёт
 * работы из общего курсора по возрастанию, а стадии идут друг за другом. Команды,
 * записанные вне параллельных стадий (феромоны, касания игрока), получают ключ «после
 * последней стадии» ([endStage]) — и в буфере тоже не нарушают порядок.
 *
 * Балансировка нагрузки не страдает: раздача работы остаётся динамической, меняется
 * только порядок применения команд, а он и так однопоточный.
 */
class WorkOrder(bufferCount: Int) {

    /** Ключ текущей работы для каждого буфера. Читает WorldCommandBuffer.push. */
    @JvmField
    var keys = LongArray(bufferCount)

    private var stage = 0L

    fun resize(bufferCount: Int) {
        keys = LongArray(bufferCount)
    }

    /** Поток симуляции, начало параллельной стадии: её номер. */
    fun beginStage(): Long = ++stage

    /** Работа [work] стадии [stage] пишет в буфер [buffer]. Зовёт воркер перед работой. */
    fun enter(buffer: Int, stage: Long, work: Int) {
        keys[buffer] = key(stage, work)
    }

    /** Стадия кончилась: всё, что запишут дальше вне стадий, идёт после неё. */
    fun endStage(stage: Long) {
        keys.fill(key(stage, AFTER_STAGE))
    }

    private fun key(stage: Long, work: Int): Long = (stage shl 32) or (work.toLong() and 0xFFFFFFFFL)

    private companion object {
        /** Номер «работы» для команд вне стадий — больше любого настоящего. */
        const val AFTER_STAGE = -1
    }
}
