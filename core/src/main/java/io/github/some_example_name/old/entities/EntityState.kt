package io.github.some_example_name.old.entities

import it.unimi.dsi.fastutil.ints.IntArrayList
import kotlin.reflect.KProperty0

/**
 * Поля сущности для сохранения мира.
 *
 * Сущность перечисляет свои поля ОДИН раз — в [Entity.persistFields], — и этот же список
 * работает и на запись, и на чтение: что делать с полем, решает реализация. Поэтому запись
 * и чтение не могут разойтись, как это бывает, когда поле добавили в сохранение и забыли
 * в загрузку.
 *
 * Поля адресуются по имени, а не по порядку. Поле, которого нет в сохранении (его добавили
 * в код позже), остаётся со значением по умолчанию; поле из сохранения, которого больше нет
 * в коде, пропускается. Так старые сохранения переживают добавление полей.
 *
 * ЧТО ПЕРЕЧИСЛЯТЬ
 * ---------------
 * Только то, что нельзя восстановить из других данных. Индексы-ускорители (карты по паре
 * клеток, пространственная сетка) пересобираются после загрузки в [Entity.restoreAfterLoad]:
 * хранить их — значит хранить вторую копию, которая может разойтись с первой.
 *
 * Массивы, индексируемые слотом сущности, пишутся только до lastId включительно: всё
 * дальше — запас ёмкости, и в нём и так лежат значения по умолчанию.
 */
interface EntityState {

    /** true — поля читаются из сохранения в сущность, false — пишутся из сущности в сохранение. */
    val isReading: Boolean

    /** Массив по слотам сущности; [perSlot] — сколько элементов приходится на один слот. */
    fun ints(field: KProperty0<IntArray>, perSlot: Int = 1)
    fun floats(field: KProperty0<FloatArray>)
    fun booleans(field: KProperty0<BooleanArray>)
    fun bytes(field: KProperty0<ByteArray>)

    /** Список целиком: содержимое заменяется сохранённым. */
    fun intList(field: KProperty0<IntArrayList>)

    /** Одно число. При записи возвращает [value], при чтении — сохранённое (или [value], если его нет). */
    fun int(name: String, value: Int): Int

    /**
     * Структура, которую сущность упаковывает в массив сама. При записи вызывается [write],
     * при чтении — [read] с сохранённым массивом (не вызывается, если поля в сохранении нет).
     */
    fun packed(name: String, write: () -> IntArray, read: (IntArray) -> Unit)
}
