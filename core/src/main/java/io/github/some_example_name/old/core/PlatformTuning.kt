package io.github.some_example_name.old.core

import com.badlogic.gdx.Application
import com.badlogic.gdx.Gdx

/**
 * Параметры пула воркеров, зависящие от платформы.
 *
 * Часть из них выводится прямо здесь через Gdx.app.type, часть обязан выставить лаунчер —
 * то, что физически требует классов платформы (приоритет потока, разбор /sys для
 * определения кластеров ядер). Всё читается на холодных путях: при создании
 * ParallelExecutor и при старте потока-воркера, — поэтому геттеры, а не константы.
 *
 * ПОЧЕМУ МОБИЛЬНЫМ НУЖНЫ ДРУГИЕ ЧИСЛА
 * -----------------------------------
 * Десктопные лимиты подобраны из соображения «спин дешевле парковки». На телефоне у этого
 * рассуждения появляется второй член: спинящее ядро — это ватты в корпусе без вентилятора.
 * Через пару минут игры срабатывает термальный троттлинг, частота CPU и GPU падает, и
 * потеря на этом больше, чем выигрыш на барьере. Поэтому спин укорочен примерно в 20 раз:
 * его хватает на промежуток между стадиями внутри тика, но не на то, чтобы греть SoC.
 */
object PlatformTuning {

    /** true на Android и iOS. Gdx.app == null только в тестах и headless-утилитах. */
    val isMobile: Boolean
        get() {
            val app = Gdx.app ?: return false
            return app.type == Application.ApplicationType.Android ||
                app.type == Application.ApplicationType.iOS
        }

    /**
     * Число «быстрых» ядер, пригодных под спинящих воркеров. 0 — определять по
     * availableProcessors().
     *
     * Выставляется лаунчером, потому что определить это переносимо нельзя: ART возвращает
     * из availableProcessors() значение sysconf(_SC_NPROCESSORS_CONF), то есть все ядра
     * всех кластеров без учёта аффинити. На типичном 1+3+4 это 8, из которых четыре —
     * little-ядра, вдвое-втрое медленнее. Динамическая раздача чанков частично это гасит
     * (медленное ядро просто возьмёт меньше чанков), но не гасит главного: воркеров не
     * должно быть столько же, сколько ядер, потому что рядом живёт GL-поток. Как только
     * планировщик вытеснит поток симуляции посреди стадии, остальные будут спинить,
     * ожидая его.
     */
    var performanceCoreCount = 0

    /**
     * Вызывается в начале каждого потока-воркера (и потока симуляции с id 0).
     *
     * Нужен для приоритета: Thread.priority маппится на nice очень грубо, а планировщик
     * Android к nice чувствителен сильно, и ядер мало. Если воркер получил приоритет ниже
     * главного, главный спинит весь свой лимит, отбирая такты у того самого воркера,
     * которого ждёт, — инверсия приоритетов на спин-барьере. Важно именно равенство
     * приоритетов потока симуляции и воркеров, а не их абсолютная величина.
     */
    var onWorkerThreadStart: (workerId: Int) -> Unit = {}

    /** Сколько итераций воркер спинит, прежде чем парковаться. */
    val workerSpinLimit: Int
        get() = if (isMobile) 1_000 else 20_000

    /** Сколько итераций главный поток спинит на барьере, прежде чем уступить ядро. */
    val mainSpinLimit: Int
        get() = if (isMobile) 4_000 else 200_000

    /**
     * Уступка ядра главным потоком после исчерпания спина. 0 — Thread.yield().
     *
     * На Android yield под CFS на загруженном устройстве часто возвращается немедленно и
     * превращается в тот же busy-loop. parkNanos — настоящий futex-сон, который реально
     * отдаёт ядро воркеру, которого мы ждём.
     */
    val mainParkNanos: Long
        get() = if (isMobile) 10_000L else 0L

    /** Потолок таймаута парковки воркера в активном режиме. */
    val parkNanosMax: Long
        get() = if (isMobile) 50_000_000L else 2_000_000L

    /**
     * Потолок таймаута парковки, когда приложение свёрнуто.
     *
     * При обычных 2 мс каждый воркер просыпался бы 500 раз в секунду вечно — в фоне это
     * заметный расход батареи на пустом месте.
     */
    val backgroundParkNanos: Long
        get() = 200_000_000L
}
