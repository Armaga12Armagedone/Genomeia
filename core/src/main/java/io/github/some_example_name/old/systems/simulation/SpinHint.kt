package io.github.some_example_name.old.systems.simulation

/**
 * Портируемая обёртка над Thread.onSpinWait().
 *
 * ЗАЧЕМ
 * -----
 * Thread.onSpinWait() появился в Java 9 и в Android — только на API 33. Модуль core
 * собирается как обычная JVM-библиотека под JVM_21, поэтому вызов компилируется без
 * единого предупреждения, а на устройстве с API 21-32 даёт NoSuchMethodError на первом
 * же тике симуляции. coreLibraryDesugaring здесь не помогает: десугаринг не подменяет
 * методы java.lang.Thread.
 *
 * ПОЧЕМУ ВЫЗОВ ВЫНЕСЕН В ОТДЕЛЬНЫЙ МЕТОД
 * --------------------------------------
 * Проверки `if (SUPPORTED)` прямо в спин-петле было бы недостаточно. Верификатор ART,
 * встретив неразрешимый метод, помечает soft-fail НЕ отдельную инструкцию, а весь метод,
 * в котором она находится, и исключает его из AOT-компиляции. То есть workerLoop и
 * runChunks уехали бы в интерпретатор на всех старых устройствах — это хуже, чем падение,
 * потому что выглядит как «просто почему-то медленно». Изолируя вызов в отдельном
 * методе, мы отдаём верификатору только его.
 *
 * ПОЧЕМУ ПРОБА ВЫЗОВОМ, А НЕ РЕФЛЕКСИЯ
 * ------------------------------------
 * Class.getMethod здесь был бы естественнее, но модуль core собирается ещё и под TeaVM,
 * где рефлексия работает только по явной конфигурации, а неучтённый getMethod падает или
 * возвращает мусор. Проба прямым вызовом не добавляет в код ни одной ссылки сверх той,
 * что и так была, поэтому не меняет условий сборки ни для одной платформы.
 *
 * ЦЕНА ПРОВЕРКИ
 * -------------
 * SPIN_WAIT_SUPPORTED — top-level val, то есть private static final поле. И JIT, и ART
 * сворачивают чтение инициализированного static final в константу и убирают ветку
 * целиком, поэтому в горячей петле проверка стоит ноль. Проба выполняется один раз при
 * загрузке класса.
 *
 * ПРО ПУСТОЙ ФОЛБЭК
 * -----------------
 * На ARM onSpinWait компилируется в инструкцию YIELD, которая на большинстве ядер Cortex
 * является подсказкой планировщику SMT, а физически близка к NOP. Поэтому пустое тело на
 * старых API — не деградация: петля всё равно упирается в volatile-чтение epoch.
 */
private val SPIN_WAIT_SUPPORTED: Boolean = try {
    onSpinWaitIntrinsic()
    true
} catch (_: Throwable) {
    false
}

/** Подсказка процессору «это spin-loop». На Android ниже API 33 — пустышка. */
fun spinPause() {
    if (SPIN_WAIT_SUPPORTED) onSpinWaitIntrinsic()
}

private fun onSpinWaitIntrinsic() {
    Thread.onSpinWait()
}
