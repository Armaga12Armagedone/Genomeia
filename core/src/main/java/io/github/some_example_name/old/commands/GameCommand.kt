package io.github.some_example_name.old.commands

/**
 * Любое действие игрока: переход между экранами, нажатие в меню, правка генома в
 * редакторе, касание мира в симуляции.
 *
 * ПРАВИЛО: всё, что игрок меняет в игре, проходит через команду и её обработчик
 * (`handle` у ViewModel, `putUiCommand` у редактора генома, `performCommand` у навигации,
 * `push` у мира). Экран только собирает команду из жеста и показывает результат — сам
 * он состояние не трогает. Поэтому каждое действие ровно один раз попадает в журнал
 * ([io.github.some_example_name.old.core.log.ActionLog]), и по журналу сценарий
 * повторяется без пересказа.
 *
 * Отсюда требования к самой команде:
 *  - только данные: числа, строки, перечисления, данные генома. Никаких ссылок на виджеты,
 *    лямбд и живых объектов — команда должна пережить запись в файл и чтение обратно;
 *  - всё случайное и всё, что зависит от платформы, решается ДО создания команды и
 *    лежит в ней значением (сид, «левый ли это клик»). Иначе повтор на другой машине
 *    пойдёт по другой ветке.
 *
 * Ввод вида (масштаб и сдвиг камеры) тоже команды: на мир он не влияет, но без него
 * по журналу не увидеть то, что видел игрок.
 */
interface GameCommand {
    /**
     * Стабильное имя для журнала. Строкой, а не `this::class.simpleName`: имена классов
     * режет минификатор, а журнал должен читаться и из релизной сборки.
     */
    val name: String

    /** Короткая сводка параметров. Сводка, а не дамп: журнал читают глазами. */
    val detail: String get() = ""
}

/** Имя с параметрами в одну строку — для краш-репорта и маршрута по экранам. */
val GameCommand.logName: String
    get() = if (detail.isEmpty()) name else "$name($detail)"
